#!/usr/bin/env python3
"""Build the Author Column copies of prosilver's topic list templates.

The extension replaces prosilver's viewforum_body.html and search_results.html
with copies that add an Author column, because phpBB has no template event in
the places the column needs. This script makes those copies from a phpBB git
checkout, so they can be rebuilt whenever prosilver changes.

Inputs: a phpBB git checkout and the git refs to read for phpBB 3.3 and 4.0.
Outputs: styles/prosilver/template/phpbb33/ and phpbb40/ in this extension,
one copy of each template per branch. Each edit must match exactly once; if
prosilver's markup changed so that an edit no longer fits, the script stops
without writing anything and names the edit, so the change can be reviewed.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

EXTENSION_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_ROOT = EXTENSION_ROOT / 'styles' / 'prosilver' / 'template'
PROSILVER_TEMPLATE_PATH = 'phpBB/styles/prosilver/template/'

# Block variable that holds each topic in the template's topic loop
TEMPLATES = {
    'viewforum_body.html': 'topicrow',
    'search_results.html': 'searchresults',
}

BRANCH_DIRECTORIES = {
    'phpbb33': 'phpBB 3.3',
    'phpbb40': 'phpBB 4.0',
}

# Stylesheets each branch's copies load, from styles/prosilver/theme/
BRANCH_STYLESHEETS = {
    'phpbb33': ['authorcolumn.css'],
    'phpbb40': ['authorcolumn.css', 'authorcolumn_40.css'],
}


def build_header(filename: str, directory: str, ref: str, commit: str) -> str:
    """Return the comment and stylesheet lines put at the top of a copy."""
    branch_label = BRANCH_DIRECTORIES[directory]
    stylesheets = ''.join(
        f"{{% INCLUDECSS '@phpbbmodders_authorcolumn/{name}' %}}\n"
        for name in BRANCH_STYLESHEETS[directory]
    )
    return (
        '{#\n'
        f'\tAuthor Column: prosilver\'s {filename} for {branch_label}\n'
        f'\t(phpBB git ref {ref}, commit {commit}) with an Author column added.\n'
        '\tGenerated by tools/build_templates.py; rebuild it rather than\n'
        '\tediting this file by hand.\n'
        '#}\n'
        + stylesheets
    )


def edits_for(block: str) -> list[tuple[str, re.Pattern, str]]:
    """Return (description, pattern, replacement) for each template edit."""
    replies_cell = (
        r'^(?P<indent>[ \t]*)(?P<cell><dd class="posts">\{'
        + re.escape(block)
        + r'\.(?:TOPIC_)?REPLIES\} <dfn>\{L_REPLIES\}</dfn></dd>)$'
    )
    return [
        (
            'header list class',
            re.compile(r'<ul class="topiclist">(?P<rest>\s*<li class="header">)'),
            r'<ul class="topiclist author-column">\g<rest>',
        ),
        (
            'topic list class',
            re.compile(r'<ul class="topiclist topics">'),
            '<ul class="topiclist topics author-column">',
        ),
        (
            'Author heading',
            re.compile(r'^(?P<indent>[ \t]*)(?P<cell><dd class="posts">\{L_REPLIES\}</dd>)$', re.M),
            '\\g<indent><dd class="author">{L_AUTHOR}</dd>\n\\g<indent>\\g<cell>',
        ),
        (
            'Author cell',
            re.compile(replies_cell, re.M),
            '\\g<indent><dd class="author"><span><dfn>{L_AUTHOR} </dfn>{'
            + block
            + '.TOPIC_AUTHOR_FULL}</span></dd>\n\\g<indent>\\g<cell>',
        ),
    ]


def resolve_commit(phpbb_repo: Path, ref: str) -> str:
    """Return the short commit hash a git ref points to."""
    result = subprocess.run(
        ['git', '-C', str(phpbb_repo), 'rev-parse', '--short=10', f'{ref}^{{commit}}'],
        capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f'unknown git ref {ref}: {result.stderr.strip()}')
    return result.stdout.strip()


def read_template(phpbb_repo: Path, ref: str, filename: str) -> str:
    """Read one prosilver template from a git ref of the phpBB checkout."""
    result = subprocess.run(
        ['git', '-C', str(phpbb_repo), 'show', f'{ref}:{PROSILVER_TEMPLATE_PATH}{filename}'],
        capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f'cannot read {filename} at {ref}: {result.stderr.strip()}')
    return result.stdout


def build_copy(source: str, filename: str, block: str, directory: str, ref: str,
               commit: str) -> str:
    """Apply every edit to one template and return the finished copy."""
    branch_label = BRANCH_DIRECTORIES[directory]
    for description, pattern, replacement in edits_for(block):
        source, count = pattern.subn(replacement, source)
        if count != 1:
            raise RuntimeError(
                f'{filename} ({branch_label}, {ref}): "{description}" matched '
                f'{count} times, expected once; check prosilver\'s markup'
            )
    return build_header(filename, directory, ref, commit) + source


def parse_args() -> argparse.Namespace:
    """Parse command-line options."""
    parser = argparse.ArgumentParser(
        description="Build the Author Column copies of prosilver's topic list templates "
                    'from a phpBB git checkout.',
    )
    parser.add_argument(
        '-p', '--phpbb-repo', type=Path, required=True,
        help='path to a phpBB git checkout that has both refs',
    )
    parser.add_argument(
        '-3', '--ref-33', required=True,
        help='git ref to read the phpBB 3.3 templates from, e.g. release-3.3.19',
    )
    parser.add_argument(
        '-4', '--ref-40', required=True,
        help='git ref to read the phpBB 4.0 templates from, e.g. upstream/master',
    )
    parser.add_argument(
        '-n', '--dry-run', action='store_true',
        help='check that every edit applies, without writing any files',
    )
    return parser.parse_args()


def main() -> int:
    """Build every copy in memory first, then write them all."""
    if len(sys.argv) == 1:
        sys.argv.append('--help')
    args = parse_args()
    refs = {'phpbb33': args.ref_33, 'phpbb40': args.ref_40}

    copies: dict[Path, str] = {}
    try:
        for directory in BRANCH_DIRECTORIES:
            commit = resolve_commit(args.phpbb_repo, refs[directory])
            for filename, block in TEMPLATES.items():
                source = read_template(args.phpbb_repo, commit, filename)
                copies[TEMPLATE_ROOT / directory / filename] = build_copy(
                    source, filename, block, directory, refs[directory], commit)
    except RuntimeError as error:
        print(f'error: {error}', file=sys.stderr)
        return 1

    for path, content in copies.items():
        if args.dry_run:
            print(f'would write {path.relative_to(EXTENSION_ROOT)}')
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
        print(f'wrote {path.relative_to(EXTENSION_ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
